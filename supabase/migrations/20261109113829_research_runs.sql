-- Phase 4-lite: research runs, stage statuses, briefings, cited sources and claims, usage
-- (ARCHITECTURE §6.0.4; D36, D38 §3, D39 §2). Backend only: RLS on, no policies, written with the service key.
-- Only cited sources and the final briefing are stored, not the raw intermediate research.

-- ---------------------------------------------------------------- research_runs
create table public.research_runs (
  id uuid primary key,                                   -- generated by the backend (also used in logs)
  created_by uuid references public.profiles (id) on delete set null,   -- null for CLI / demo runs
  company text not null,
  request jsonb not null,                                -- the validated ResearchRequest
  status text not null default 'running' check (status in ('running', 'completed', 'partial', 'failed')),
  depth text not null check (depth in ('quick', 'standard', 'in_depth')),
  language text not null check (language in ('en', 'he')),
  meeting_type text not null check (meeting_type in ('sales', 'partnership')),
  prompt_versions jsonb not null default '{}'::jsonb,    -- per role (D29)
  depth_config jsonb not null default '{}'::jsonb,       -- app/research/depth.py values used (D38 §4)
  search_languages text[] not null default '{}',
  rounds int not null default 0 check (rounds >= 0),
  llm_calls int not null default 0 check (llm_calls >= 0),
  input_tokens int not null default 0 check (input_tokens >= 0),
  output_tokens int not null default 0 check (output_tokens >= 0),
  tavily_credits int not null default 0 check (tavily_credits >= 0),
  quality jsonb,                                         -- QualityReport
  error text,
  started_at timestamptz not null default now(),
  finished_at timestamptz
);
create index research_runs_created_by_idx on public.research_runs (created_by);
create index research_runs_started_idx on public.research_runs (started_at desc);

-- ---------------------------------------------------------------- run_stages
create table public.run_stages (
  run_id uuid not null references public.research_runs (id) on delete cascade,
  stage text not null check (stage in ('company_identification', 'internal_research', 'external_research',
                                       'competitor_analysis', 'strategic_analysis', 'briefing_writing',
                                       'quality_checks')),
  status text not null default 'pending'
    check (status in ('pending', 'in_progress', 'completed', 'failed', 'skipped')),
  detail text,
  attempts int not null default 0 check (attempts >= 0),
  started_at timestamptz,
  finished_at timestamptz,
  primary key (run_id, stage)
);

-- ---------------------------------------------------------------- briefings
create table public.briefings (
  id uuid primary key default gen_random_uuid(),
  run_id uuid not null unique references public.research_runs (id) on delete cascade,
  company text not null,
  language text not null check (language in ('en', 'he')),
  meeting_type text not null check (meeting_type in ('sales', 'partnership')),
  content jsonb not null,                                -- the Briefing contract (immutable original)
  markdown text not null,
  is_partial boolean not null default false,
  is_sample boolean not null default false,              -- D39: shown to public visitors in demo mode
  created_at timestamptz not null default now()
);
create index briefings_created_idx on public.briefings (created_at desc);
create index briefings_sample_idx on public.briefings (created_at desc) where is_sample;

-- The AI-generated original never changes. Only the demo flag may be toggled.
create or replace function public.briefings_immutable()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.content is distinct from old.content or new.markdown is distinct from old.markdown
     or new.run_id is distinct from old.run_id or new.language is distinct from old.language then
    raise exception 'briefings are immutable (only is_sample can change)';
  end if;
  return new;
end;
$$;
create trigger briefings_immutable before update on public.briefings
  for each row execute function public.briefings_immutable();

-- ---------------------------------------------------------------- sources (cited only)
create table public.sources (
  id uuid primary key default gen_random_uuid(),
  briefing_id uuid not null references public.briefings (id) on delete cascade,
  ref text not null,                                     -- run source ID cited in claims (I1, W3)
  position int not null check (position >= 1),           -- [n] in the rendered briefing
  kind text not null check (kind in ('internal', 'external')),
  title text not null,
  url text,
  outlet text,
  published_at timestamptz,
  tier smallint check (tier between 1 and 4),
  source_type text,
  language text,
  citation text,                                         -- internal: "file § section"
  document_id uuid references public.documents (id) on delete set null,
  document_version int,
  unique (briefing_id, ref)
);
create index sources_document_id_idx on public.sources (document_id);

-- ---------------------------------------------------------------- claims
create table public.claims (
  id uuid primary key default gen_random_uuid(),
  briefing_id uuid not null references public.briefings (id) on delete cascade,
  section text not null,                                 -- 'summary' or one of the 12 section keys
  position int not null check (position >= 0),
  text text not null,
  info_type text not null check (info_type in ('external_fact', 'internal_document', 'user_provided',
                                               'ai_analysis', 'ai_recommendation', 'unverified')),
  source_refs text[] not null default '{}',
  confidence text check (confidence in ('high', 'medium', 'low')),
  is_conflict boolean not null default false,
  conflicting_refs text[] not null default '{}',
  importance text check (importance in ('High', 'Medium', 'Low')),   -- opportunities / risks only
  unique (briefing_id, section, position)
);

-- ---------------------------------------------------------------- usage_events
create table public.usage_events (
  id bigint generated always as identity primary key,
  run_id uuid references public.research_runs (id) on delete cascade,
  kind text not null check (kind in ('llm', 'tavily')),
  agent text not null,                                   -- research / analysis / writer / quality / identification
  model text,
  input_tokens int not null default 0 check (input_tokens >= 0),
  output_tokens int not null default 0 check (output_tokens >= 0),
  credits int not null default 0 check (credits >= 0),
  created_at timestamptz not null default now()
);
create index usage_events_run_id_idx on public.usage_events (run_id);
create index usage_events_created_idx on public.usage_events (created_at);

-- ---------------------------------------------------------------- access: backend only
alter table public.research_runs enable row level security;
alter table public.run_stages enable row level security;
alter table public.briefings enable row level security;
alter table public.sources enable row level security;
alter table public.claims enable row level security;
alter table public.usage_events enable row level security;
revoke all on public.research_runs, public.run_stages, public.briefings, public.sources, public.claims,
              public.usage_events from anon, authenticated;
revoke all on function public.briefings_immutable() from public, anon, authenticated;
